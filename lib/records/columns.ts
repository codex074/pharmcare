export function codeLabel(table: string, column: string, v: unknown): unknown {
  const opts = CODE_LABELS[table]?.[column]
  if (!opts) return v
  if (Array.isArray(v)) return v.map((x) => opts[x as string] ?? x)
  return v == null ? null : (opts[v as string] ?? v)
}
