export function educationTopics(device: Device): readonly string[] {
  return EDUCATION_TOPICS[CHECKLISTS[device].group]
}

// A fresh, unassessed copy of a device's checklist for a new assessment.
export function buildStepSnapshot(device: Device): AssessedStep[] {
  return CHECKLISTS[device].steps.map((s) => ({ text: s.text, critical: s.critical, result: null }))
}
